CREATE OR REPLACE TABLE INSURANCE_ML.ML_PIPE.INSURANCE_SPLIT AS
SELECT
    *,
    ROW_NUMBER() OVER (ORDER BY RANDOM()) AS ROW_NUM
FROM INSURANCE_ML.ML_PIPE.INSURANCE_TRAINING;

CREATE OR REPLACE TABLE INSURANCE_ML.ML_PIPE.INSURANCE_TRAIN AS
SELECT
    AGE,
    SEX,
    BMI,
    CHILDREN,
    SMOKER,
    REGION,
    CHARGES
FROM INSURANCE_ML.ML_PIPE.INSURANCE_SPLIT
WHERE ROW_NUM <= (
    SELECT COUNT(*) * 0.80
    FROM INSURANCE_ML.ML_PIPE.INSURANCE_SPLIT
);

CREATE OR REPLACE TABLE INSURANCE_ML.ML_PIPE.INSURANCE_TEST AS
SELECT
    AGE,
    SEX,
    BMI,
    CHILDREN,
    SMOKER,
    REGION,
    CHARGES
FROM INSURANCE_ML.ML_PIPE.INSURANCE_SPLIT
WHERE ROW_NUM > (
    SELECT COUNT(*) * 0.80
    FROM INSURANCE_ML.ML_PIPE.INSURANCE_SPLIT
);

SELECT
    'TRAIN' AS DATASET,
    COUNT(*) AS ROW_COUNT
