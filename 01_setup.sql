CREATE OR REPLACE PROCEDURE INSURANCE_ML.ML_PIPE.PROCESS_INSURANCE_PREDICTIONS()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN

    INSERT INTO INSURANCE_ML.ML_PIPE.INSURANCE_PREDICTIONS
    (
        AGE,
        SEX,
        BMI,
        CHILDREN,
        SMOKER,
        REGION,
        ACTUAL_CHARGES,
        PREDICTED_CHARGES
    )
    SELECT
        AGE,
        SEX,
        BMI,
        CHILDREN,
        SMOKER,
        REGION,
        CHARGES AS ACTUAL_CHARGES,

        MODEL(
            INSURANCE_ML.ML_PIPE.INSURANCE_CHARGES_MODEL,
            V2
        )!predict(
            AGE,
            SEX,
            BMI,
            CHILDREN,
            SMOKER,
            REGION
        ):output_feature_0::FLOAT AS PREDICTED_CHARGES

    FROM INSURANCE_ML.ML_PIPE.INSURANCE_INCOMING_STREAM
    WHERE METADATA$ACTION = 'INSERT';

    RETURN 'Insurance predictions processed successfully';

END;
$$;


